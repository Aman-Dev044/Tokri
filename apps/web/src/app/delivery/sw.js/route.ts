/**
 * The rider service worker, served at `/delivery/sw.js`.
 *
 * ── WHY IT IS A ROUTE AND NOT A FILE IN /public ─────────────────────────────
 * A service worker can only control paths at or below its own URL. A worker
 * served from `/public/sw.js` would sit at the origin root and control the
 * entire site — the shop, the vendor console, the admin console — which is
 * emphatically not this worker's business. Serving it from `/delivery/sw.js`
 * scopes it to `/delivery/` by construction, with no `Service-Worker-Allowed`
 * header games and no chance of it leaking into someone else's surface.
 *
 * ── WHAT IT DOES ────────────────────────────────────────────────────────────
 * One job: the app OPENS when the network does not. A rider halfway through a
 * delivery who rides into a basement must still be able to see the job, the
 * address and the phone number. So:
 *
 *   navigations under /delivery  → network first, cache fallback, then the
 *                                  cached shell, then a plain offline page
 *   /_next/static/*              → cache first (immutable, content-hashed)
 *   everything else              → straight to the network, uncached
 *
 * The job data itself is NOT cached here — it is mirrored into sessionStorage
 * by `RiderProvider`, which the shell reads on boot and labels as cached. A
 * service worker cache is shared across tabs and survives sign-out; a
 * customer's address and phone number should not live there.
 *
 * ── WHAT A BROWSER PWA CANNOT DO, STATED PLAINLY ────────────────────────────
 *   · NO reliable background location. The OS suspends a backgrounded tab
 *     within seconds to minutes. `periodicsync` is Chrome-only, permissioned,
 *     and fires at the browser's discretion — it is not a tracker.
 *   · NO background push without a push subscription and a VAPID key, neither
 *     of which exists in this build. A new offer only reaches a rider whose
 *     app is open. That is why the offer screen is built around a 45-second
 *     countdown the rider is looking at.
 *   · NO guaranteed delivery of a queued location fix. There is no Background
 *     Sync here; a killed tab loses its queue.
 *
 * These are accepted, not worked around (plan §8.7, challenge #16). A future
 * React Native shell fixes all three and the BACKEND DOES NOT CHANGE: same
 * REST endpoints (§6.2), same socket contract (§6.3), same OTP flow. Nothing
 * in the API is shaped around this worker.
 */

import { APP_NAME } from '@/config/brand';

/**
 * The cache-bucket discriminator, fixed once per server process.
 *
 * A service worker is reinstalled only when its BYTES change. With a
 * hardcoded version the generated source was identical on every build, so
 * the browser saw nothing to update and `activate` — which clears every
 * cache whose name is not the current `VERSION` — had nothing to clear.
 * The shell a rider cached weeks ago survived every deploy.
 *
 * Module scope, NOT inside the handler: computing this per request would
 * change the worker's bytes on every fetch and leave it reinstalling
 * itself forever.
 */
const BUILD_STAMP = Date.now().toString(36);

const SOURCE = String.raw`
/* ${APP_NAME} rider service worker — generated by app/delivery/sw.js/route.ts */

const VERSION = '${APP_NAME.toLowerCase()}-rider-${BUILD_STAMP}';
const SHELL_URL = '/delivery';
const OFFLINE_KEYS = [SHELL_URL];

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(VERSION);
      // A failure here must not block the install — a rider whose first load
      // raced a flaky connection should still get a worker.
      await Promise.allSettled(OFFLINE_KEYS.map((url) => cache.add(url)));
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n !== VERSION).map((n) => caches.delete(n)));
      await self.clients.claim();
    })(),
  );
});

/**
 * The last-resort page. Inline, so it needs nothing from the network — which
 * means these colours cannot come from tokens.css either; nothing on this
 * page can fetch anything. They are hand-copied from Neon Orchard's ground,
 * ink, mint and on-accent tokens (light and dark) so a rider who loses signal
 * mid-shift lands on the same palette, not a flash of something else. Same
 * reasoning as the two hex values in delivery/layout.tsx's viewport.themeColor.
 */
const OFFLINE_HTML = [
  '<!doctype html><html lang="en"><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">',
  '<title>Offline · ${APP_NAME} Rider</title><style>',
  ':root{color-scheme:light dark}',
  'body{margin:0;min-height:100dvh;display:grid;place-items:center;padding:1.5rem;',
  'background:#faf7ff;color:#170e22;font:600 1rem/1.5 system-ui,-apple-system,"Segoe UI",sans-serif;text-align:center}',
  '@media (prefers-color-scheme:dark){body{background:#0e0a14;color:#f4eefb}}',
  'h1{font-size:1.6rem;margin:0 0 .5rem}p{margin:0 0 1.25rem;max-width:32ch}',
  'button{min-height:64px;padding:0 1.5rem;font:inherit;font-size:1.1rem;font-weight:800;',
  'border-radius:18px;border:3px solid #0aa96a;background:#0aa96a;color:#fff}',
  '@media (prefers-color-scheme:dark){button{border-color:#2bf5a0;background:#2bf5a0;color:#06180f}}',
  '</style></head><body><main><h1>No connection</h1>',
  '<p>${APP_NAME} cannot be reached right now. Your delivery has not been lost &mdash; reconnect and it will still be here.</p>',
  '<button type="button" onclick="location.reload()">Try again</button>',
  '</main></body></html>',
].join('');

function offlineResponse() {
  return new Response(OFFLINE_HTML, {
    status: 200,
    headers: { 'Content-Type': 'text/html; charset=utf-8' },
  });
}

self.addEventListener('fetch', (event) => {
  const request = event.request;

  // Never touch a mutation. A replayed POST /deliver is a delivered order.
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Same-origin only. The API and the socket live elsewhere and must never be
  // served from a cache — a stale job or a stale offer is worse than an error.
  if (url.origin !== self.location.origin) return;

  // Content-hashed build assets: safe to cache forever.
  if (url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/icons/')) {
    event.respondWith(
      (async () => {
        const cached = await caches.match(request);
        if (cached) return cached;
        const response = await fetch(request);
        if (response.ok) {
          const cache = await caches.open(VERSION);
          void cache.put(request, response.clone());
        }
        return response;
      })(),
    );
    return;
  }

  // Page navigations inside the rider app.
  if (request.mode === 'navigate' && url.pathname.startsWith('/delivery')) {
    event.respondWith(
      (async () => {
        try {
          const response = await fetch(request);
          if (response.ok && response.type === 'basic') {
            const cache = await caches.open(VERSION);
            void cache.put(request, response.clone());
          }
          return response;
        } catch (error) {
          const cached = (await caches.match(request)) || (await caches.match(SHELL_URL));
          return cached || offlineResponse();
        }
      })(),
    );
  }
});

/* Let the page tell a waiting worker to take over, so a rider is never stuck
   on a stale build after an update lands mid-shift. */
self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') void self.skipWaiting();
});
`;

export function GET(): Response {
  return new Response(SOURCE, {
    headers: {
      'Content-Type': 'text/javascript; charset=utf-8',
      // The worker is served from /delivery/ so its default scope is already
      // /delivery/. This header is belt-and-braces and documents the intent.
      'Service-Worker-Allowed': '/delivery/',
      // Never let a proxy pin an old worker: that is how a rider ends up on a
      // build from three deploys ago with no way to escape it.
      'Cache-Control': 'no-cache, no-store, must-revalidate',
    },
  });
}
