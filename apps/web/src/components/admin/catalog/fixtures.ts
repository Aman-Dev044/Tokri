/**
 * SAMPLE DATA — not real, never presented as real.
 *
 * Covers `/admin/categories` and `/admin/products`. Shown only when those
 * endpoints cannot be reached, always behind an amber banner.
 *
 * `aisleKey` is the field that drives the chromatic aisle UI in the shopping
 * app (plan §5.1). Here it is only a grouping and a swatch — the admin surface
 * does not re-tint itself.
 *
 * Money is INTEGER PAISE. Stock lives in `inventory`, never on the product doc
 * (plan §5.2) — the `stock` field below is the joined inventory value.
 */

import type { AisleKey } from '@mandi/design-system';

export interface CategoryRow {
  id: string;
  name: string;
  slug: string;
  aisleKey: AisleKey;
  /** null ⇒ platform-global, otherwise scoped to one vendor */
  vendorId: string | null;
  vendorName: string | null;
  parentId: string | null;
  sortOrder: number;
  productCount: number;
  isActive: boolean;
}

export type ProductUnit = 'kg' | 'g' | 'l' | 'ml' | 'piece' | 'pack';

export interface ProductRow {
  id: string;
  name: string;
  brand: string | null;
  sku: string;
  vendorId: string;
  vendorName: string;
  categoryId: string;
  categoryName: string;
  aisleKey: AisleKey;
  unit: ProductUnit;
  unitValue: number;
  pricePaise: number;
  mrpPaise: number;
  stock: number;
  lowStockThreshold: number;
  isActive: boolean;
  updatedAt: string;
}

/** The editable slice of a category — what the drawer form writes back. */
export interface CategoryDraft {
  name: string;
  slug: string;
  aisleKey: AisleKey;
  sortOrder: number;
  isActive: boolean;
}

